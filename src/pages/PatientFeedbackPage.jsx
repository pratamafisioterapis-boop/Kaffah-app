import React, { useEffect, useState } from 'react';
import { useParams } from 'react-router-dom';
import { supabase, supabaseUrl, supabaseAnonKey } from '@/lib/customSupabaseClient';
import { Star, Loader2, AlertTriangle, CheckCircle2, ExternalLink } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Textarea } from '@/components/ui/textarea';
import { PRAXIS_CLINIC_ID } from '@/lib/clinicIds';

// Kuesioner khusus Praxis, dilanjutkan ke Google Review.
const SCALE = ['Sangat Puas', 'Puas', 'Cukup Puas', 'Tidak Puas', 'Sangat Tidak Puas'];
const PRAXIS_QUESTIONS = [
  { id: 'reg', label: 'Kemudahan proses Pendaftaran / Administrasi / Reservasi', options: SCALE },
  { id: 'wait', label: 'Waktu Anda menunggu hingga dilayani', options: ['< 10 Menit', '10 - 20 menit', '> 20 Menit'] },
  { id: 'info', label: 'Petugas Pendaftaran memberikan informasi layanan dengan jelas', options: ['Ya', 'Tidak'] },
  { id: 'service', label: 'Layanan yang dijalani di {clinic}', options: ['Layanan Dokter', 'Layanan Fisioterapi', 'Layanan Keperawatan'] },
  { id: 'listen', label: 'Tenaga Medis Dokter / Fisioterapis / Keperawatan mendengarkan keluhan dengan baik', options: SCALE },
  { id: 'care', label: 'Pelayanan dan Tindakan oleh Tenaga Medis Dokter / Fisioterapis / Keperawatan', options: SCALE },
  { id: 'clean', label: 'Kebersihan dan Kenyamanan Ruang tunggu', options: SCALE },
  { id: 'facility', label: 'Fasilitas pendukung (toilet, AC, parkir)', options: SCALE },
  { id: 'overall', label: 'Kepuasan pelayanan di {clinic} secara menyeluruh', options: SCALE },
  { id: 'return', label: 'Saya bersedia kembali berobat ke klinik ini di masa depan', options: ['Ya', 'Tidak', 'Ragu-ragu'] },
];

// Public, no-login page opened from a shareable link (e.g.
// /feedback/<token>) generated by clinic staff for one patient. Captures a
// star rating + optional comment via submit_patient_feedback(); a 4-5 star
// rating gets an onward link to the clinic's Google review page (only when
// the clinic has a google_place_id configured) so the same visit can also
// become a public Google review, while low ratings stay internal.
const PatientFeedbackPage = () => {
  const { token } = useParams();
  const [status, setStatus] = useState('loading'); // loading | form | already | invalid | submitted
  const [clinicName, setClinicName] = useState('');
  const [rating, setRating] = useState(0);
  const [hoverRating, setHoverRating] = useState(0);
  const [comment, setComment] = useState('');
  const [submitting, setSubmitting] = useState(false);
  const [googleReviewUrl, setGoogleReviewUrl] = useState(null);
  const [isPraxis, setIsPraxis] = useState(false);
  const [answers, setAnswers] = useState({});
  const [staffName, setStaffName] = useState('');

  useEffect(() => {
    let cancelled = false;

    const fetchLink = async () => {
      const { data, error } = await supabase
        .rpc('get_feedback_link_info', { p_token: token })
        .maybeSingle();

      if (cancelled) return;

      if (error || !data) {
        setStatus('invalid');
        return;
      }

      setClinicName(data.clinic_name || '');
      const { data: cid } = await supabase.rpc('get_feedback_link_clinic_id', { p_token: token });
      if (cancelled) return;
      setIsPraxis(cid === PRAXIS_CLINIC_ID);
      setStatus(data.already_responded ? 'already' : 'form');
    };

    if (token) fetchLink();
    else setStatus('invalid');

    return () => { cancelled = true; };
  }, [token]);

  const handleSubmit = async () => {
    if (rating < 1) return;
    setSubmitting(true);
    const { data, error } = await supabase
      .rpc('submit_patient_feedback', { p_token: token, p_rating: rating, p_comment: comment })
      .maybeSingle();
    setSubmitting(false);

    if (error || !data?.success) {
      setStatus('already');
      return;
    }

    setGoogleReviewUrl(data.google_review_url || null);
    setStatus('submitted');
  };

  // Praxis: simpan kuesioner lalu langsung buka halaman Google Review.
  const praxisComplete = PRAXIS_QUESTIONS.every((q) => answers[q.id]);
  const handlePraxisSubmit = async () => {
    if (!praxisComplete) return;
    const name = clinicName || 'Praxis';
    const overallRating = 5 - SCALE.indexOf(answers.overall); // Sangat Puas=5 ... Sangat Tidak Puas=1
    const lines = PRAXIS_QUESTIONS.map((q) => `${q.label.replace('{clinic}', name)}: ${answers[q.id]}`);
    if (staffName.trim()) lines.push(`Petugas terbaik: ${staffName.trim()}`);
    if (comment.trim()) lines.push(`Saran & Masukan: ${comment.trim()}`);
    setSubmitting(true);
    const { data, error } = await supabase
      .rpc('submit_praxis_feedback', { p_token: token, p_rating: overallRating, p_comment: lines.join('\n') })
      .maybeSingle();
    setSubmitting(false);
    if (error || !data?.success) {
      setStatus('already');
      return;
    }
    if (data.google_review_url) {
      window.location.href = data.google_review_url;
      return;
    }
    setStatus('submitted');
  };

  // Fires via fetch(..., { keepalive: true }) instead of supabase.rpc(): the
  // anchor below navigates away immediately after this click (often to the
  // *same* tab, since many in-app browsers -- WhatsApp, Instagram -- ignore
  // target="_blank" and reuse the current webview). A plain supabase-js call
  // is an ordinary fetch that gets cancelled the instant the page unloads,
  // so the click can be silently lost; keepalive keeps the request alive
  // past unload, same as navigator.sendBeacon.
  const handleGoogleReviewClick = () => {
    try {
      fetch(`${supabaseUrl}/rest/v1/rpc/mark_feedback_google_review_clicked`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          apikey: supabaseAnonKey,
          Authorization: `Bearer ${supabaseAnonKey}`,
        },
        body: JSON.stringify({ p_token: token }),
        keepalive: true,
      }).catch(() => {});
    } catch (_) {
      // best-effort click tracking; never block navigation to Google
    }
  };

  return (
    <div className="min-h-screen flex items-center justify-center bg-gradient-to-br from-slate-900 via-indigo-950 to-slate-900 p-4">
      <div className="w-full max-w-md bg-white rounded-2xl shadow-2xl overflow-hidden">
        <div className="bg-gradient-to-br from-indigo-600 to-indigo-800 px-6 py-8 text-center text-white">
          <div className="mx-auto w-14 h-14 rounded-full bg-white/15 flex items-center justify-center mb-3">
            <Star className="w-7 h-7" />
          </div>
          <h1 className="text-lg font-bold">Bagaimana Pengalaman Anda?</h1>
          {clinicName && <p className="text-indigo-200 text-sm mt-0.5">{clinicName}</p>}
        </div>

        <div className="p-6">
          {status === 'loading' && (
            <div className="py-6 flex flex-col items-center gap-3 text-slate-500">
              <Loader2 className="w-6 h-6 animate-spin" />
              <p className="text-sm">Menyiapkan form feedback...</p>
            </div>
          )}

          {status === 'invalid' && (
            <div className="py-6 flex flex-col items-center gap-3 text-red-500 text-center">
              <AlertTriangle className="w-8 h-8" />
              <p className="text-sm text-slate-600">Link feedback tidak ditemukan atau sudah tidak berlaku.</p>
            </div>
          )}

          {status === 'already' && (
            <div className="py-6 flex flex-col items-center gap-3 text-center">
              <CheckCircle2 className="w-8 h-8 text-green-500" />
              <p className="text-sm text-slate-600">Terima kasih, feedback untuk link ini sudah pernah dikirim sebelumnya.</p>
            </div>
          )}

          {status === 'form' && isPraxis && (
            <div className="space-y-5">
              <p className="text-sm text-slate-600 text-center">
                Kami ingin mendengar pendapat atau masukan Anda agar kami dapat menyempurnakan pengalaman Anda!
              </p>
              {PRAXIS_QUESTIONS.map((q) => (
                <fieldset key={q.id} className="space-y-2">
                  <legend className="text-sm font-medium text-slate-800">
                    {q.label.replace('{clinic}', clinicName || 'Praxis')} <span className="text-red-500">*</span>
                  </legend>
                  <div className="flex flex-wrap gap-2">
                    {q.options.map((opt) => (
                      <button
                        key={opt}
                        type="button"
                        onClick={() => setAnswers((a) => ({ ...a, [q.id]: opt }))}
                        className={`px-3 py-1.5 rounded-full border text-sm transition-colors ${
                          answers[q.id] === opt
                            ? 'bg-indigo-600 border-indigo-600 text-white'
                            : 'bg-white border-slate-200 text-slate-600 hover:border-indigo-300'
                        }`}
                      >
                        {opt}
                      </button>
                    ))}
                  </div>
                </fieldset>
              ))}
              <div className="space-y-2">
                <label className="text-sm font-medium text-slate-800">
                  Nama petugas kami yang telah memberikan pelayanan terbaik (opsional)
                </label>
                <input
                  value={staffName}
                  onChange={(e) => setStaffName(e.target.value)}
                  className="w-full rounded-md border border-slate-200 px-3 py-2 text-sm"
                />
              </div>
              <div className="space-y-2">
                <label className="text-sm font-medium text-slate-800">
                  Saran &amp; Masukan sangat berharga untuk perbaikan pelayanan (opsional)
                </label>
                <Textarea value={comment} onChange={(e) => setComment(e.target.value)} rows={3} />
              </div>
              <Button
                onClick={handlePraxisSubmit}
                disabled={!praxisComplete || submitting}
                className="w-full bg-indigo-600 hover:bg-indigo-700"
              >
                {submitting && <Loader2 className="w-4 h-4 animate-spin mr-2" />} Kirim &amp; Lanjut ke Google Review
              </Button>
            </div>
          )}

          {status === 'form' && !isPraxis && (
            <div className="space-y-5">
              <div className="flex justify-center gap-2">
                {Array.from({ length: 5 }).map((_, i) => {
                  const value = i + 1;
                  const filled = value <= (hoverRating || rating);
                  return (
                    <button
                      key={value}
                      type="button"
                      onClick={() => setRating(value)}
                      onMouseEnter={() => setHoverRating(value)}
                      onMouseLeave={() => setHoverRating(0)}
                      className="p-1"
                      aria-label={`${value} bintang`}
                    >
                      <Star className={`w-9 h-9 transition-colors ${filled ? 'fill-amber-400 text-amber-400' : 'text-slate-200'}`} />
                    </button>
                  );
                })}
              </div>
              <Textarea
                placeholder="Ceritakan pengalaman Anda (opsional)"
                value={comment}
                onChange={(e) => setComment(e.target.value)}
                rows={4}
              />
              <Button
                onClick={handleSubmit}
                disabled={rating < 1 || submitting}
                className="w-full bg-indigo-600 hover:bg-indigo-700"
              >
                {submitting && <Loader2 className="w-4 h-4 animate-spin mr-2" />} Kirim Feedback
              </Button>
            </div>
          )}

          {status === 'submitted' && (
            <div className="py-4 flex flex-col items-center gap-4 text-center">
              <CheckCircle2 className="w-10 h-10 text-green-500" />
              <p className="text-sm text-slate-600">Terima kasih atas feedback Anda!</p>
              {googleReviewUrl && (
                <>
                  <p className="text-sm text-slate-500">
                    Senang mendengarnya! Mau bantu klinik dengan membagikan ulasan singkat di Google?
                  </p>
                  <a
                    href={googleReviewUrl}
                    target="_blank"
                    rel="noreferrer"
                    className="w-full"
                    onClick={handleGoogleReviewClick}
                  >
                    <Button className="w-full bg-blue-600 hover:bg-blue-700">
                      <ExternalLink className="w-4 h-4 mr-2" /> Tulis Ulasan di Google
                    </Button>
                  </a>
                </>
              )}
            </div>
          )}
        </div>
      </div>
    </div>
  );
};

export default PatientFeedbackPage;
